using System;
using System.Collections.Generic;
using System.Text;

namespace Bangun_Datar
{
    internal class Trapesium
    {
        public double luas(double a, double b, double t)
        {
            return 0.5 * (a + b) * t;
        }

        public double keliling(double a, double b, double c, double d)
        {
            return a + b + c + d;
        }


    }
}
