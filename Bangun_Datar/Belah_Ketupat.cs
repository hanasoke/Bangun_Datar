using System;
using System.Collections.Generic;
using System.Text;

namespace Bangun_Datar
{
    internal class Belah_Ketupat
    {
        public double luas(double d1, double d2)
        {
            return 0.5 * d1 * d2;
        }

        public double keliling(double s)
        {
            return 4 * s;
        }
    }
}
