using System;
using System.Collections.Generic;
using System.Text;

namespace Bangun_Datar
{
    internal class Layang_Layang
    {
        public double luas(double d1, double d2)
        {
            return 0.5 * d1 * d2;
        }

        public double keliling(double a, double b)
        {
            return 2 * (a + b);
        }
    }
