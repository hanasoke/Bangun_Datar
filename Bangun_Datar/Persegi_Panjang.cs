using System;
using System.Collections.Generic;
using System.Text;

namespace Bangun_Datar
{
    internal class Persegi_Panjang
    {
        public double luas_persegi_panjang(double p, double l)
        {
            return p * l;
        }

        public double keliling_persegi_panjang(double p, double l)
        {
            return 2 * (p + l);
        }

    }
}
