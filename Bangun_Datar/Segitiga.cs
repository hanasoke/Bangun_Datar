using System;
using System.Collections.Generic;
using System.Text;

namespace Bangun_Datar
{
    internal class Segitiga
    {
        public double luas(double a, double t)
        {
            return 0.5 * a * t;
        }

        public double keliling(double a, double b, double c)
        {
            return a + b + c;
        }
    }
